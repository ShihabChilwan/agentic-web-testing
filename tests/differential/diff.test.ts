describe('shapes, duplicates, changed requests and setup findings', () => {
  it('learns a random tail and flags a value that loses it', () => {
    // Mixed-case random tails: `_` and `-` are allowed although these two never show them.
    expect(observeShape('tools-OznBKCxVve', 'tools-VQHlHzF7AL')).toEqual({ kind: 'tail', types: ['string'], tailLength: [10, 10], tailChars: '-9A_a' });
    const shape = observeShape('tools-OznBKCxVve', 'tools-VQHlHzF7AL');
    expect(fitsShape('tools-OznBKCxVve', 'tools-D_DfCbZgM9', shape)).toBe(true);
    expect(fitsShape('tools-OznBKCxVve', 'tools', shape)).toBe(false);
    // A tail that starts with a delimiter still fits.
    expect(fitsShape('industrial--K-exw-1Oz', 'industrial-4nqpXMXEaQ', shape)).toBe(true);
    expect(fitsShape('industrial--K-exw-1Oz', 'industrial', shape)).toBe(false);
    expect(fitsShape('2026-11-10T10:00:00Z', '2026-11-10T11:00:00Z', observeShape('2026-11-10T09:00:00Z', '2026-11-10T09:05:00Z'))).toBe(true);
    expect(fitsShape(5, 'x', observeShape(4, 7))).toBe(false);
    // Only the digit runs that varied in the correct runs may vary: the time, not the price.
    const row = observeShape('Placed 10:05 total $12.50', 'Placed 10:09 total $12.50');
    expect(row).toMatchObject({ kind: 'digits', digitRuns: [0], runCount: 2 });
    expect(fitsShape('Placed 10:05 total $12.50', 'Placed 11:07 total $12.50', mergeShapes(row, observeShape('Placed 10:05 total $12.50', 'Placed 10:06 total $12.50')))).toBe(true);
    expect(fitsShape('Placed 10:05 total $12.50', 'Placed 10:07 total $13.50', row)).toBe(false);
  });

  it('a slug that loses its suffix and a duplicate slug are strong', () => {
    const list = (slugs: string[]) => [res('TC-001', 1, 'GET', '/api/c', { items: slugs.map((slug, i) => ({ id: i, slug })) })];
    const noise = findNoise([list(['tools', 'tools-OznBKCxVve']), list(['tools', 'tools-VQHlHzF7AL']), list(['tools', 'tools-kD-O_sfOUr'])], { ...meta, executions: ['x-01', 'x-02', 'x-03'] });
    expect(noise.endpoints[0]!.fields[0]).toMatchObject({ field: 'items[*].slug', unique: true, shape: { kind: 'tail', tailLength: [10, 10] } });
    const c = compareResponses(list(['tools', 'tools-OznBKCxVve']), list(['tools', 'tools']), noise, cmeta);
    expect(c.tests[0]!.endpoints[0]!.differences.map((d) => [d.field, d.reason, d.other])).toEqual([
      ['items[*].slug', 'shape', 'tools'],
      ['items[*].slug(duplicate)', 'duplicate', ['tools']],
    ]);
    expect(compareResponses(list(['tools', 'tools-OznBKCxVve']), list(['tools', 'tools-D_DfCbZgM9']), noise, cmeta).summary.remaining).toBe(0);
  });

  it('a request with other query values is one strong difference, unless the correct runs vary it', () => {
    const call = (t: string, q: string): RecordedResponse => ({ ...res(t, 1, 'GET', `/api/list?sort=${q}&page=1`, { n: q }), source: 'page' });
    const c = compareResponses([call('TC-001', 'desc')], [call('TC-001', 'asc')], null, cmeta);
    expect(c.tests[0]!.endpoints[0]).toMatchObject({ endpoint: 'GET /api/list?sort=*&page=:id', differences: [{ field: '(request)', base: 'sort=desc&page=:id', other: 'sort=asc&page=:id', strength: 'strong', reason: 'request' }] });
    const noise = findNoise([[call('TC-001', 'desc')], [call('TC-001', 'asc')]], meta);
    expect(compareResponses([call('TC-001', 'desc')], [call('TC-001', 'up')], noise, cmeta).summary.remaining).toBe(0);
  });

  it('folds id-alias differences into one setup finding when the other run shares no seeded ids', () => {
    const hex = (n: number) => (0x6af302ba9c0b1b2a7eb20000n + BigInt(n)).toString(16);
    const shared = Array.from({ length: 60 }, (_, i) => hex(i));
    const golden = ['TC-001', 'TC-002'].map((t) => res(t, 1, 'GET', '/api/x', { items: shared.map((_id, i) => ({ _id, n: i })) }));
    const reseeded = ['TC-001', 'TC-002'].map((t, k) => res(t, 1, 'GET', '/api/x', { items: shared.map((_, i) => ({ _id: hex(1000 * (k + 1) + i), n: i })) }));
    const c = compareResponses(golden, reseeded, null, cmeta);
    expect(c.findings).toHaveLength(1);
    expect(c.findings[0]).toMatchObject({ kind: 'setup-changed', count: 120 });
    expect(c.findings[0]!.message).toMatch(/snapshot failed \/ re-seeded/);
    expect(c.summary).toMatchObject({ strong: 1, weak: 0, remaining: 1 });
  });
});

describe('page snapshots', () => {
  const snap = (rows: string[]) => ['- banner:', '  - link "Store"', '- main:', '  - heading "Orders" [level=1]', '  - table:', ...rows.map((r) => `    - row "${r}"`)].join('\n');
  const page = (t: string, text: string | null, kind: 'navigation' | 'end' = 'end') => pageRecords([{ testCaseId: t, seq: 1, kind, path: '/orders', snapshot: text }]);

  it('reads role paths and diffs lines: a changed text pairs up, an extra line stands alone', () => {
    expect(ariaLines(snap(['A']))).toEqual([
      { path: 'banner', text: 'banner' },
      { path: 'banner>link', text: 'link "Store"' },
      { path: 'main', text: 'main' },
      { path: 'main>heading', text: 'heading "Orders" [level=1]' },
      { path: 'main>table', text: 'table' },
      { path: 'main>table>row', text: 'row "A"' },
    ]);
    expect(diffPageText(snap(['A', 'B']), snap(['A', 'C', 'D']))).toEqual([
      { field: 'main>table>row', path: 'main>table>row#1', a: 'row "B"', b: 'row "C"' },
      { field: 'main>table>row(line)', path: 'main>table>row', a: '(absent)', b: 'row "D"' },
    ]);
  });

  it('learns page noise like response noise: a time in a row is noise, a new button is strong', () => {
    const at = (t: string) => snap([`Placed ${t}`]);
    const noise = findNoise([page('TC-001', at('2026-11-10T10:00:00Z')), page('TC-001', at('2026-11-10T10:05:00Z')), page('TC-001', at('2026-11-10T10:09:00Z'))], { ...meta, executions: ['x-01', 'x-02', 'x-03'] });
    expect(noise.endpoints.map((e) => [e.endpoint, e.fields.map((f) => [f.field, f.shape?.kind])])).toEqual([['END /orders', [['main>table>row', 'digits']]]]);
    expect(compareResponses(page('TC-001', at('2026-11-10T10:00:00Z')), page('TC-001', at('2026-11-10T11:30:00Z')), noise, cmeta).summary.remaining).toBe(0);
    const extra = compareResponses(page('TC-001', at('2026-11-10T10:00:00Z')), page('TC-001', `${at('2026-11-10T11:30:00Z')}\n  - button "Delete"`), noise, cmeta);
    // A line on one side only is weak (timing can cause it); a changed line is strong.
    expect(extra.tests[0]!.endpoints[0]!.differences).toMatchObject([{ field: 'main>button(line)', base: '(absent)', other: 'button "Delete"', strength: 'weak' }]);
    const changed = compareResponses(page('TC-001', snap(['Total $12'])), page('TC-001', snap(['Total $13'])), null, cmeta);
    expect(changed.tests[0]!.endpoints[0]!.differences).toMatchObject([{ field: 'main>table>row', strength: 'strong' }]);
  });
});

describe('strong and weak differences', () => {
  it('a browser call in one run only is weak; an api response in one run only, or a changed value, is strong', () => {
    const page = (t: string, seq: number, body: unknown): RecordedResponse => ({ ...res(t, seq, 'GET', '/api/me', body), source: 'page' });
    const a = [page('TC-001', 1, { n: 1 }), res('TC-002', 1, 'GET', '/api/x', { n: 1 }), res('TC-003', 1, 'GET', '/api/y', { n: 1 })];
    const b = [res('TC-003', 1, 'GET', '/api/y', { n: 2 })];
    const c = compareResponses(a, b, null, cmeta);
    expect(c.summary).toMatchObject({ remaining: 3, strong: 2, weak: 1 });
    expect(c.tests.map((t) => [t.testCaseId, t.endpoints[0]!.differences[0]!.strength])).toEqual([['TC-001', 'weak'], ['TC-002', 'strong'], ['TC-003', 'strong']]);
  });
});

