const res = (testCaseId: string, seq: number, method: string, path: string, body: unknown, status = 200): RecordedResponse => ({
  testCaseId, seq, source: 'api', method, path, status, contentType: 'application/json', bodyKind: 'json', body,
});
const meta = { run: 'r', sourceRunId: 'r', executions: ['x-01', 'x-02'], now: new Date('2026-11-10T00:00:00Z') };
const cmeta = { run: 'r', base: 'x-01', other: 'x-03', noiseFile: 'noise-fields.json', now: new Date('2026-11-10T00:00:00Z') };

describe('endpointOf', () => {
  it('replaces id-like path parts and long numbers, keeps the rest', () => {
    expect(endpointOf('get', '/api/product/65a1b2c3d4e5f60718293a4b')).toBe('GET /api/product/:id');
    expect(endpointOf('GET', '/api/links/3f2b8c1e-1d2a-4b5c-8d9e-0a1b2c3d4e5f/stats')).toBe('GET /api/links/:id/stats');
    expect(endpointOf('GET', '/api/product/item/shirt-1793377322013?page=2&id=65a1b2c3d4e5f60718293a4b')).toBe('GET /api/product/item/shirt-<now>?page=:id&id=:id');
    expect(endpointOf('POST', '/api/cart/add')).toBe('POST /api/cart/add');
    expect(endpointOf('GET', '/api/product/item/product-mwamek4k-s42hoy')).toBe('GET /api/product/item/product-<uniq>');
    expect(endpointOf('GET', '/api/merchant/search?search=active--mwami5ue-telr52@example.test')).toBe('GET /api/merchant/search?search=active--<uniq>@example.test');
    expect(endpointOf('GET', '/api/v2/links/generic-steel-gloves')).toBe('GET /api/v2/links/generic-steel-gloves');
  });
});

describe('normaliseGenerated', () => {
  it('replaces the scripts\' generated values and ids inside text, nothing else', () => {
    expect(normaliseGenerated('product-mwamecth-gxrf78')).toBe('product-<uniq>');
    expect(normaliseGenerated('cat-mwamei0k-aioktn description')).toBe('cat-<uniq> description');
    expect(normaliseGenerated('Dup Merchant 1794311103303')).toBe('Dup Merchant <now>');
    expect(normaliseGenerated('tc091-1794310982966@example.test')).toBe('tc091-<now>@example.test');
    expect(normaliseGenerated('Cannot find Address with the id: 6af302eb9c0b1b2a7eb22f71.')).toBe('Cannot find Address with the id: <id>.');
    // Not generated by a script: unchanged.
    expect(normaliseGenerated('small-bronze-soap-Bk9sQJc6tw')).toBe('small-bronze-soap-Bk9sQJc6tw');
    expect(normaliseGenerated('updated-mwamectt-gjr2qp') === normaliseGenerated('product-mwamkm82-41njik')).toBe(false);
    expect(normaliseGenerated('ROLE MEMBER')).toBe('ROLE MEMBER');
    expect(normaliseGenerated('generic-steel-gloves')).toBe('generic-steel-gloves');
    expect(normaliseGenerated('order 1234567890123')).toBe('order 1234567890123'); // 2009: not a run's time
  });

  it('lets a path holding a generated name match across runs', () => {
    const pairs = matchResponses([res('TC-001', 1, 'GET', '/api/product/item/product-mwameksq-06j370', 1)], [res('TC-001', 1, 'GET', '/api/product/item/product-mwamkuf2-g4od6o', 1)]);
    expect(pairs.map((p) => [p.endpoint, !!p.a, !!p.b])).toEqual([['GET /api/product/item/product-<uniq>', true, true]]);
  });
});

describe('matchResponses', () => {
  it('leaves out page calls the browser cancelled (2xx, no body), not api responses', () => {
    const cancelled: RecordedResponse = { ...res('TC-001', 1, 'GET', '/api/me', null), source: 'page', bodyKind: 'none' };
    expect(matchResponses([cancelled, res('TC-001', 2, 'GET', '/api/me', 1)], [res('TC-001', 1, 'GET', '/api/me', 1)]).map((p) => [!!p.a, !!p.b])).toEqual([[true, true]]);
    const empty: RecordedResponse = { ...res('TC-001', 1, 'GET', '/api/me', null), bodyKind: 'none' };
    expect(matchResponses([empty], [])).toHaveLength(1);
  });

  it('pairs by test, endpoint and occurrence, not by arrival order', () => {
    const a = [res('TC-001', 1, 'GET', '/api/a', 1), res('TC-001', 2, 'GET', '/api/b', 2), res('TC-001', 3, 'GET', '/api/a', 3)];
    const b = [res('TC-001', 1, 'GET', '/api/b', 2), res('TC-001', 2, 'GET', '/api/a', 1), res('TC-001', 3, 'GET', '/api/a', 3)];
    const pairs = matchResponses(a, b);
    expect(pairs.map((p) => [p.endpoint, p.occurrence, p.a?.body, p.b?.body])).toEqual([
      ['GET /api/a', 1, 1, 1], ['GET /api/a', 2, 3, 3], ['GET /api/b', 1, 2, 2],
    ]);
  });

  it('keeps a response that only one side has', () => {
    const pairs = matchResponses([res('TC-001', 1, 'GET', '/api/a', 1)], []);
    expect(pairs).toHaveLength(1);
    expect(pairs[0]!.b).toBeUndefined();
  });
});

describe('id aliases through matchResponses', () => {
  it('gives the same records the same alias in two seeds, and keeps a different record visible', () => {
    const run1 = [res('TC-001', 1, 'GET', '/api/x', { items: [{ _id: '6af302ba9c0b1b2a7eb22f65' }, { _id: '6af302ba9c0b1b2a7eb22f66' }], owner: '6af302ba9c0b1b2a7eb22f66' })];
    const run2 = [res('TC-001', 1, 'GET', '/api/x', { items: [{ _id: '6af303dca8871b39ce4f50a5' }, { _id: '6af303dca8871b39ce4f50a6' }], owner: '6af303dca8871b39ce4f50a6' })];
    const bug = [res('TC-001', 1, 'GET', '/api/x', { items: [{ _id: '6af303dca8871b39ce4f50a5' }, { _id: '6af303dca8871b39ce4f50a6' }], owner: '6af303dca8871b39ce4f50a5' })];
    expect(matchResponses(run1, run2)[0]!.a!.body).toEqual({ items: [{ _id: '<id:t.1>' }, { _id: '<id:t.2>' }], owner: '<id:t.2>' });
    expect(compareResponses(run1, run2, null, cmeta).summary.differences).toBe(0);
    expect(compareResponses(run1, bug, null, cmeta).tests[0]!.endpoints[0]!.differences).toEqual([{ field: 'owner', path: 'owner', base: '<id:t.2>', other: '<id:t.1>', strength: 'strong', reason: 'value' }]);
  });

  it('an id seen in several tests keeps its alias when another test misses a record', () => {
    const ids = ['6af302ba9c0b1b2a7eb22f61', '6af302ba9c0b1b2a7eb22f62', '6af302ba9c0b1b2a7eb22f63'];
    const all = (t: string, list: string[]) => res(t, 1, 'GET', '/api/x', { items: list.map((_id) => ({ _id })) });
    const golden = [all('TC-001', ids), all('TC-002', ids), all('TC-003', ids)];
    const bug = [all('TC-001', ids), all('TC-002', ids.slice(1)), all('TC-003', ids)];
    const c = compareResponses(golden, bug, null, cmeta);
    expect(c.summary.remaining).toBe(1);
    expect(c.tests[0]!.endpoints[0]!.differences[0]).toMatchObject({ field: 'items[*]', path: 'items[_id="<id:1>"]', other: '(absent)' });
  });
});

describe('diffJson', () => {
  it('generalises array positions in the field and keeps them in the path', () => {
    const d = diffJson({ items: [{ id: 1, at: 'x' }, { id: 2, at: 'y' }] }, { items: [{ id: 1, at: 'x' }, { id: 2, at: 'z' }] });
    expect(d).toEqual([{ field: 'items[*].at', path: 'items[id=2].at', a: 'y', b: 'z' }]);
  });

  it('reports a missing key and an extra item as absent', () => {
    expect(diffJson({ a: 1, list: [1] }, { list: [1, 2] })).toEqual([
      { field: 'a', path: 'a', a: 1, b: '(absent)' },
      { field: 'list[*]', path: 'list[=2]', a: '(absent)', b: 2 },
    ]);
  });
});

describe('listKey and orderChange', () => {
  it('prefers _id or id, else another unique field shared by both sides, else plain values', () => {
    expect(listKey([{ _id: 'a', n: 1 }, { _id: 'b', n: 1 }], [{ _id: 'b', n: 1 }, { _id: 'a', n: 1 }])).toBe('_id');
    expect(listKey([{ sku: 'a', n: 1 }, { sku: 'b', n: 1 }], [{ sku: 'b', n: 1 }])).toBe('sku');
    expect(listKey([3, 1], [1, 3])).toBe('(value)');
    // A field unique on each side but never shared (e.g. a time) is not a key.
    expect(listKey([{ at: 't1', n: 1 }, { at: 't2', n: 1 }], [{ at: 't3', n: 1 }, { at: 't4', n: 1 }])).toBeUndefined();
    expect(orderChange([{ x: [1] }, { x: [2] }], [{ x: [2] }, { x: [1] }])).toBe('(item)');
    expect(orderChange([{ _id: 'a' }, { _id: 'b' }], [{ _id: 'a' }, { _id: 'b' }])).toBeUndefined();
  });

  it('reports one missing item as one difference, and a changed order as one difference', () => {
    const list = [{ _id: 'a', p: 1 }, { _id: 'b', p: 2 }, { _id: 'c', p: 3 }];
    expect(diffJson({ items: list }, { items: list.slice(1) })).toEqual([{ field: 'items[*]', path: 'items[_id="a"]', a: list[0], b: '(absent)' }]);
    expect(diffJson({ items: list }, { items: [...list].reverse() })).toEqual([
      { field: 'items[*](order)', path: 'items(order by _id)', a: ['a', 'b', 'c'], b: ['c', 'b', 'a'] },
    ]);
  });
});

describe('findNoise and compareResponses', () => {
  const golden1 = [
    res('TC-001', 1, 'POST', '/api/product', { product: { _id: '65a1b2c3d4e5f60718293a4b', name: 'Shirt', price: 10, created: '2026-11-10T10:00:00Z' } }),
    res('TC-002', 1, 'GET', '/api/product/list', { products: [{ _id: 'a', price: 5 }, { _id: 'b', price: 7 }] }),
  ];
  const golden2 = [
    res('TC-001', 1, 'POST', '/api/product', { product: { _id: '65a1b2c3d4e5f60718293fff', name: 'Shirt', price: 10, created: '2026-11-10T10:05:00Z' } }),
    res('TC-002', 1, 'GET', '/api/product/list', { products: [{ _id: 'b', price: 7 }, { _id: 'a', price: 5 }] }),
  ];

  it('lists the fields that differ per endpoint (ids aliased) and the lists whose order changed, without marking reordered fields as noise', () => {
    const noise = findNoise([golden1, golden2], meta);
    expect(noise.endpoints).toEqual([
      { endpoint: 'GET /api/product/list', fields: [], unstableOrder: [{ array: 'products', key: '_id', tests: ['TC-002'] }] },
      {
        endpoint: 'POST /api/product',
        fields: [
          { field: 'product.created', tests: ['TC-001'], count: 1, example: { a: '2026-11-10T10:00:00Z', b: '2026-11-10T10:05:00Z' }, shape: { kind: 'time', types: ['string'] } },
        ],
        unstableOrder: [],
      },
    ]);
    expect(noise.summary).toMatchObject({ matched: 2, unmatched: 0, noiseFields: 1, unstableOrderLists: 1 });
  });

  it('a third golden run leaves nothing; a real change is kept, also inside a reordered list', () => {
    const noise = findNoise([golden1, golden2], meta);
    const golden3 = [
      res('TC-001', 1, 'POST', '/api/product', { product: { _id: '65a1b2c3d4e5f60718290000', name: 'Shirt', price: 10, created: '2026-11-10T11:00:00Z' } }),
      res('TC-002', 1, 'GET', '/api/product/list', { products: [{ _id: 'b', price: 7 }, { _id: 'a', price: 5 }] }),
    ];
    expect(compareResponses(golden1, golden3, noise, cmeta).summary).toMatchObject({ remaining: 0, ignoredAsNoise: 1 });

    const bug = [
      res('TC-001', 1, 'POST', '/api/product', { product: { _id: '65a1b2c3d4e5f60718290000', name: 'Shirt', price: 0, created: 'x' } }, 201),
      res('TC-002', 1, 'GET', '/api/product/list', { products: [{ _id: 'b', price: 8 }, { _id: 'a', price: 5 }] }),
    ];
    const c = compareResponses(golden1, bug, noise, cmeta);
    expect(c.tests).toEqual([
      { testCaseId: 'TC-001', endpoints: [{ endpoint: 'POST /api/product', occurrence: 1, differences: [
        { field: '(status)', path: '(status)', base: 200, other: 201, strength: 'strong', reason: 'value' },
        // 'x' is not a time: outside the shape the correct runs showed for this noise field.
        { field: 'product.created', path: 'product.created', base: '2026-11-10T10:00:00Z', other: 'x', strength: 'strong', reason: 'shape' },
        { field: 'product.price', path: 'product.price', base: 10, other: 0, strength: 'strong', reason: 'value' },
      ] }] },
      { testCaseId: 'TC-002', endpoints: [{ endpoint: 'GET /api/product/list', occurrence: 1, differences: [
        { field: 'products[*].price', path: 'products[_id="b"].price', base: 7, other: 8, strength: 'strong', reason: 'value' },
      ] }] },
    ]);
  });

  it('a list with a stable order is still compared by position, so a reordering bug is caught', () => {
    const sorted = [res('TC-003', 1, 'GET', '/api/x', { list: [{ id: 1 }, { id: 2 }] })];
    const reversed = [res('TC-003', 1, 'GET', '/api/x', { list: [{ id: 2 }, { id: 1 }] })];
    const noise = findNoise([sorted, sorted], meta);
    expect(compareResponses(sorted, reversed, noise, cmeta).tests[0]!.endpoints[0]!.differences.map((d) => d.field)).toEqual(['list[*](order)']);
  });
});

