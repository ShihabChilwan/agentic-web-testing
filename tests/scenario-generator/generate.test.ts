const textOf = (req: ChatRequest) => req.messages.flatMap((m) => m.content.flatMap((b) => (b.type === 'text' ? [b.text] : b.type === 'tool_result' ? [b.content] : []))).join('\n');
const firstText = (req: ChatRequest) => {
  const first = req.messages[0];
  return first?.role === 'user' && first.content[0]?.type === 'text' ? first.content[0].text : '';
};
const turns = (req: ChatRequest) => req.messages.filter((m) => m.role === 'assistant').length;

/** The fake model: discovery sessions read code (and try forbidden paths), then submit; script sessions submit a light body. */
function fakeModel(): { llm: FakeLLMClient; requests: ChatRequest[] } {
  const requests: ChatRequest[] = [];
  const respond = (req: ChatRequest): ChatResponse => {
    requests.push(structuredClone(req));
    const task = firstText(req);
    if (req.purpose === 'scenarios') {
      const feature = /feature (F-\d+)\./.exec(task)?.[1];
      const n = turns(req);
      if (n === 0) {
        return FakeLLMClient.toolCalls([
          { name: 'read_file', input: { path: '../variants.json' } },
          { name: 'read_file', input: { path: '../../targets/fake/sealed-2/variants.json' } },
          { name: 'list_files', input: { path: '..' } },
          { name: 'search', input: { pattern: 'sort' } },
          { name: 'read_file', input: { path: 'server/items.js' } },
        ]);
      }
      if (feature !== 'F-01') return FakeLLMClient.toolCall('submit_variation_points', { points: [] });
      const base = { layer: 'api', endpoint: 'GET /api/items', setup: ['Create three items with different names as users.alice'], user: 'users.alice', citation: { file: 'server/items.js', lines: [1, 7] } };
      const points = [
        { ...base, kind: 'unused-option', description: 'Sort by the newest item, a sort value no test sent.', values: n === 1 ? ['oldest'] : ['newest'], action: 'Send GET /api/items?sort=newest' },
        { ...base, kind: 'unused-option', description: 'Sort descending, a sort value no test sent.', values: ['desc'], action: 'Send GET /api/items?sort=desc' },
        { ...base, kind: 'list', description: 'The list with three items sorted by name.', values: [], records: 3, action: 'Send GET /api/items?sort=asc' },
        { ...base, kind: 'boundary', endpoint: 'POST /api/items', description: 'A name of exactly 64 characters, the longest allowed.', values: [], setup: [], action: 'Send POST /api/items with a 64-character name', citation: { file: 'server/items.js', lines: [13, 18] } },
      ];
      return FakeLLMClient.toolCall('submit_variation_points', { points });
    }
    // Script sessions.
    const ui = /\(ui test case\)/.test(task);
    return FakeLLMClient.toolCall('submit_script', {
      body: ui
        ? "await page.goto('/items');\nawait expect(page.locator('body'), 'E1').toBeVisible();"
        : "const res = await api.get('/api/items');\nexpect(res.status(), 'E1').toBeGreaterThan(99);",
    });
  };
  return { llm: new FakeLLMClient(Array.from({ length: 400 }, () => respond)), requests };
}

describe('generateScenarios', () => {
  it('adds checked scenario tests in their own folders, drops failing and unstable ones, refills once, and never shows a planted bug', async () => {
    const { llm, requests } = fakeModel();
    const sourceScripts = await readFile(path.join(runsDir, sourceFolder, 'scripts', 'TC-001.spec.ts'), 'utf8');
    const checks: string[][] = [];
    let checkRuns = 0;
    const result = await generateScenarios({
      from: sourceFolder,
      runsDir,
      targetsDir: path.join(root, 'targets'),
      projectRoot: root,
      cap: 4,
      llmConfig: parseLLMConfig({ LLM_BASE_URL: 'http://m/v1' }),
      createLlm: async () => llm,
      startApp: async () => ({ restore: async () => ({ durationMs: 1 }), stop: async () => {} }),
      snapshotPage: async () => null,
      // The third scenario never passes its dry run (an error without an E-id).
      runDryRun: async (_runDir, file) =>
        /SC-003/.test(file) ? { status: 'failed', message: 'TypeError: cannot read properties of undefined', durationMs: 1 } : { status: 'passed', message: '', durationMs: 1 },
      // In the second check run of round 1, the first scenario fails: unstable.
      runCheck: async ({ runDir, scriptsDir }) => {
        checkRuns++;
        const manifest = ScriptManifest.parse(JSON.parse(await readFile(path.join(runDir, scriptsDir, 'manifest.json'), 'utf8')));
        const ids = manifest.scripts.map((e) => e.testCaseId);
        checks.push(ids);
        const results = { results: ids.map((id, i) => ({ testCaseId: id, status: checkRuns === 2 && i === 0 ? 'failed' : 'passed' })) } as unknown as ExecutionResults;
        return { results, responses: [] } satisfies CheckRun;
      },
    });

    const folder = `${sourceFolder}-scn`;
    expect(result.runId).toBe(folder);
    const dir = path.join(runsDir, folder);
    const summary = ScenarioSummary.parse(JSON.parse(await readFile(path.join(dir, 'scenarios', 'summary.json'), 'utf8')));
    expect(summary.status).toBe('done');

    // Points: the model's (after one rejected submit) and the role points made by code.
    const points = VariationPoints.parse(JSON.parse(await readFile(path.join(dir, 'scenarios', 'variation-points.json'), 'utf8')));
    expect(points.points.filter((p) => p.origin === 'model').map((p) => [p.kind, p.values])).toEqual([
      ['unused-option', ['newest']],
      ['unused-option', ['desc']],
      ['list', []],
      ['boundary', []],
    ]);
    expect(points.points.filter((p) => p.origin === 'code').length).toBeGreaterThan(5);
    expect(points.points.find((p) => p.values.includes('newest'))!.unrunLines).toBe(true);
    expect(points.selected).toHaveLength(4);
    expect(summary.discovery).toMatchObject({ sessions: 2, failedSessions: 0, rejected: 1 });

    // Round 1: SC-001..SC-004; SC-003 invalid, SC-001 unstable. Round 2 refills two from the reserve.
    expect(checks[0]).toEqual(['SC-001', 'SC-002', 'SC-004']);
    expect(checks[2]).toEqual(['SC-005', 'SC-006']);
    expect(summary.dropped.map((d) => [d.id, d.reason])).toEqual([['SC-003', 'invalid'], ['SC-001', 'unstable-outcome']]);
    expect(summary.kept).toEqual(['SC-002', 'SC-004', 'SC-005', 'SC-006']);
    const cases = ScenarioCases.parse(JSON.parse(await readFile(path.join(dir, 'scenarios', 'scenarios.json'), 'utf8'))).cases;
    expect(cases.map((c) => c.id)).toEqual(['SC-001', 'SC-002', 'SC-003', 'SC-004', 'SC-005', 'SC-006']);
    expect(cases.every((c) => c.expected.length === 1 && c.expected[0]!.value === undefined)).toBe(true);

    // The combined suite: the original script unchanged plus the kept scenarios; the original suite is untouched.
    expect(summary.combined).toEqual({ scriptsDir: 'scripts-with-scenarios', tc: 1, sc: 4 });
    const combined = ScriptManifest.parse(JSON.parse(await readFile(path.join(dir, 'scripts-with-scenarios', 'manifest.json'), 'utf8')));
    expect(combined.scripts.map((e) => [e.testCaseId, e.file])).toEqual([
      ['TC-001', 'scripts-with-scenarios/TC-001.spec.ts'],
      ...summary.kept.map((id) => [id, `scripts-with-scenarios/${id}.spec.ts`]),
    ]);
    expect(SuiteCases.parse(JSON.parse(await readFile(path.join(dir, 'scripts-with-scenarios', 'cases.json'), 'utf8'))).testCases.map((c) => c.id)).toEqual(['TC-001', ...summary.kept]);
    expect(await readFile(path.join(dir, 'scripts-with-scenarios', 'TC-001.spec.ts'), 'utf8')).toBe(sourceScripts);
    expect(await readFile(path.join(dir, 'scripts', 'TC-001.spec.ts'), 'utf8')).toBe(sourceScripts);
    expect((await readdir(path.join(dir, 'scripts'))).sort()).toEqual(['TC-001.spec.ts', '_helpers.ts', '_target.json', 'manifest.json']);
    const scenarioScript = await readFile(path.join(dir, 'scripts-with-scenarios', 'SC-002.spec.ts'), 'utf8');
    expect(scenarioScript).toMatch(/^\/\/ SC-002: /);
    expect((await readRunManifest(path.join(dir, 'run.json'))).executions).toEqual([]);

    // What the suite already does was read from the correct version's recording only ("page" values came from x-01).
    const discoveryTasks = requests.filter((r) => r.purpose === 'scenarios').map(firstText);
    expect(discoveryTasks.find((t) => t.includes('Find variation points for feature F-01'))).toContain('query values sent: page=1; sort=asc');

    // No canary, path or id of a planted bug in any prompt, task or tool output, nor anywhere in the copied run folder.
    // A refused path comes back in the tool's error as the model typed it; that echo tells nothing, so it is taken out.
    const typed = ['../variants.json', '../../targets/fake/sealed-2/variants.json'];
    for (const req of requests) {
      const shown = typed.reduce((t, p) => t.split(`"${p}"`).join('"<typed path>"'), `${req.system}\n${textOf(req)}`);
      const hit = FORBIDDEN.exec(shown);
      if (hit) throw new Error(`forbidden "${hit[0]}" in: ${shown.slice(Math.max(0, hit.index - 200), hit.index + 100)}`);
      for (const canary of CANARIES) expect(shown).not.toContain(canary);
      expect(shown).not.toMatch(FORBIDDEN);
    }
    const toolOutputs = requests.flatMap((r) => r.messages.flatMap((m) => m.content.flatMap((b) => (b.type === 'tool_result' ? [b.content] : []))));
    expect(toolOutputs.filter((t) => /may not contain "\.\."|does not exist/.test(t)).length).toBeGreaterThanOrEqual(3);
    const files = execFileSync('find', ['.', '-type', 'f'], { cwd: dir, encoding: 'utf8' }).split('\n').filter(Boolean);
    for (const file of files) {
      expect(file).not.toMatch(/differential|noise-fields|eval\/|x-02/);
      const text = await readFile(path.join(dir, file), 'utf8');
      for (const canary of CANARIES) expect(text, file).not.toContain(canary);
    }
    // The source run is left as it was.
    expect(await readFile(path.join(runsDir, sourceFolder, 'noise-fields.json'), 'utf8')).toContain('CANARY-NOISE');
  }, 120_000);

  it('refuses to generate twice without --fresh, and a copy that exists', async () => {
    const options = { runsDir, targetsDir: path.join(root, 'targets'), projectRoot: root, llmConfig: parseLLMConfig({ LLM_BASE_URL: 'http://m/v1' }) };
    await expect(generateScenarios({ ...options, runId: `${sourceFolder}-scn` })).rejects.toThrow(/already has scenarios/);
    await expect(generateScenarios({ ...options, from: sourceFolder })).rejects.toThrow(/exists; use --run/);
  });
});

/** In code: a planted bug's folder, file or id (the word "patch" alone is an execution field). */
const FORBIDDEN_IN_SOURCE = /sealed-2|variants|[\w-]+\.patch['"`]|runs\/variants-|differential\/compare|scoring\/|\bbug-\d{3}\b|\bdev-\d{3}\b/;

describe('the generator source', () => {
  it('names no planted-bug location or id', async () => {
    const dir = path.join(PROJECT_ROOT, 'src', 'modules', 'scenario-generator');
    for (const name of await readdir(dir)) {
      const text = await readFile(path.join(dir, name), 'utf8');
      expect(text, name).not.toMatch(FORBIDDEN_IN_SOURCE);
    }
  });
});
