const script = (id: string, layer: 'api' | 'ui', expected: string, body: string) => `// ${id}: case ${id}
// Generated by agentic-web-testing from testcases.json.
import { expect, test, uniq } from './_helpers.js';

// @locked-expected ${id}: generated from testcases.json. Do not edit.
const EXPECTED = {
${expected}
} as const;
// @end-locked-expected

test('${id}: case ${id}', async ({ ${layer === 'api' ? 'api' : 'page'} }) => {
${body}
});
`;

