const testCase = (id: string, value: number | string) => ({
  id, requirementIds: ['REQ-001'], title: `case ${id}`, layer: 'api', category: 'functional', priority: 'high',
  preconditions: [], fixturesUsed: [], steps: ['do it'], expected: [{ id: 'E1', description: 'd', value }],
});

let root: string;
