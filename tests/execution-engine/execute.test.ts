describe('executeRun (real Playwright)', () => {
  it('runs the passed scripts in one Playwright process with a restore before each test, and keeps the evidence of failures', async () => {
    const logs: string[] = [];
    const result = await executeRun({ runId, runsDir, targetsDir: path.join(root, 'targets'), projectRoot: root, log: (m) => logs.push(m) });
    expect(result.execId).toBe('x-01');
    expect(result.atGenerationRef).toBe(true);
    const execDir = path.join(runsDir, runId, 'executions', 'x-01');
    const results = ExecutionResults.parse(JSON.parse(await readFile(path.join(execDir, 'results.json'), 'utf8')));
    const byId = Object.fromEntries(results.results.map((r) => [r.testCaseId, r]));

    // Isolation: TC-002 sees only its own item; TC-004 sees a restarted backend with fresh data.
    expect(Object.fromEntries(results.results.map((r) => [r.testCaseId, r.status]))).toEqual({
      'TC-001': 'passed', 'TC-002': 'passed', 'TC-003': 'passed', 'TC-004': 'passed',
      'TC-005': 'failed', 'TC-006': 'failed', 'TC-007': 'errored',
    });
    expect(results.results.every((r) => r.isolated)).toBe(true);
    expect(results.summary).toEqual({ total: 7, passed: 4, failed: 2, errored: 1, skipped: 2, notIsolated: 0 });
    expect(results.skipped).toEqual([{ testCaseId: 'TC-008', reason: 'assertion_failed' }, { testCaseId: 'TC-009', reason: 'invalid' }]);
    expect(results.timing?.restores).toBe(7);
    // The crash during TC-003 is recorded where it was found.
    expect(results.incidents).toEqual([{ beforeTestCaseId: 'TC-004', kind: 'backend-crashed', detail: 'the backend process had exited (code 1)' }]);

    expect(byId['TC-005']?.error).toMatchObject({ expectationId: 'E1', category: 'assertion_failed' });
    expect(Object.keys(byId['TC-005']!.artifacts).sort()).toEqual(['console', 'dom', 'network', 'screenshot', 'trace']);
    expect(byId['TC-006']?.artifacts).toEqual({
      trace: 'artifacts/TC-006/trace.zip',
      lastResponse: 'artifacts/TC-006/last-response.json',
      serverLog: 'artifacts/TC-006/backend.log',
    });
    // The backend log slice holds this test's requests only.
    const slice = await readFile(path.join(execDir, 'artifacts', 'TC-006', 'backend.log'), 'utf8');
    expect(slice).toContain('GET /api/items?probe=TC-006');
    expect(slice).not.toContain('POST /api/items');
    expect(byId['TC-007']?.error).toMatchObject({ expectationId: null, category: 'runtime-error' });
    expect(byId['TC-001']?.artifacts).toEqual({});
    // Restore time is not part of a test's duration.
    expect(byId['TC-004']!.durationMs).toBeLessThan(results.timing!.restoreMs / 7 + 5000);

    // Only executions/x-01/ was written; Playwright's own output folder is gone; the run's scripts are untouched.
    expect((await readdir(execDir)).sort()).toEqual(['artifacts', 'playwright.config.ts', 'playwright.log', 'report.json', 'results.json', 'server', 'suite']);
    expect((await readdir(path.join(runsDir, runId, 'scripts'))).sort()).toEqual([...Object.keys(SCRIPTS).map((id) => `${id}.spec.ts`), '_helpers.ts', 'manifest.json'].sort());
    // Nothing in the execution folder names the ref.
    expect(JSON.stringify(results)).not.toMatch(/golden/);
    const manifest = await readRunManifest(path.join(runsDir, runId, 'run.json'));
    expect(manifest.executions).toEqual([
      { execId: 'x-01', ref: 'golden', commit: result.commit, executeStatus: 'done', analyzeStatus: 'pending' },
    ]);
    expect(logs).toContain('[7/7] TC-007');
  }, 180_000);
});

describe('executeVersion settings', () => {
  it('starts the app with the request\'s own configOverride and skipSeed (restores reuse them)', async () => {
    const seen: StartOptions[] = [];
    const runDir = path.join(runsDir, runId);
    const { config, repoDir, targetDir } = await import('../../src/shared/target-config.js').then((m) =>
      m.loadTargetConfig('fake', { targetsDir: path.join(root, 'targets'), projectRoot: root }),
    );
    await expect(
      executeVersion({
        runDir, config, repoDir, targetDir, generationRef: 'golden',
        request: { execId: 'x-90', ref: 'golden', skipSeed: true, configOverride: { backend: { env: { PORT: null } } } },
        startApp: async (options) => {
          seen.push(options);
          throw new Error('stop here');
        },
      }),
    ).rejects.toThrow('stop here');
    expect(seen[0]).toMatchObject({ ref: 'golden', generationRef: 'golden', skipSeed: true, configOverride: { backend: { env: { PORT: null } } } });
  });

  it('refuses an execution folder that already exists', async () => {
    const { config, repoDir, targetDir } = await import('../../src/shared/target-config.js').then((m) =>
      m.loadTargetConfig('fake', { targetsDir: path.join(root, 'targets'), projectRoot: root }),
    );
    await expect(
      executeVersion({ runDir: path.join(runsDir, runId), config, repoDir, targetDir, generationRef: 'golden', request: { execId: 'x-90', ref: 'golden' } }),
    ).rejects.toThrow(/already exists/);
  });

  it('refuses a bad ref before creating anything', async () => {
    await expect(
      executeRun({ runId, runsDir, targetsDir: path.join(root, 'targets'), projectRoot: root, ref: 'no-such-ref', execId: 'x-91' }),
    ).rejects.toThrow(/Unknown ref "no-such-ref"/);
    expect(await readdir(path.join(runsDir, runId, 'executions'))).not.toContain('x-91');
  });
});

describe('executeRun with a patch and skipSeed', () => {
  it('runs from a patched source tree, records patch and skipSeed, and never changes the target repo', async () => {
    const repo = path.join(root, 'targets', 'fake', 'repo');
    const patchFile = path.join(root, 'change.patch');
    // Made with git diff from a temporary edit, then the edit is undone.
    const original = await readFile(path.join(repo, 'web', 'server.cjs'), 'utf8');
    await writeFile(path.join(repo, 'web', 'server.cjs'), original.replace('<h1>Shop</h1>', '<h1>Store</h1>'));
    await writeFile(patchFile, execFileSync('git', ['-C', repo, 'diff'], { encoding: 'utf8' }));
    await writeFile(path.join(repo, 'web', 'server.cjs'), original);
    const before = await readFile(path.join(repo, 'web', 'server.cjs'), 'utf8');
    let seen: StartOptions | undefined;
    let treeFile = '';
    await expect(
      executeRun({
        runId, runsDir, targetsDir: path.join(root, 'targets'), projectRoot: root, patch: patchFile, skipSeed: true, execId: 'x-50',
        startApp: async (options) => {
          seen = options;
          treeFile = await readFile(path.join(options.repoDir, 'web', 'server.cjs'), 'utf8');
          throw new Error('stop here');
        },
      }),
    ).rejects.toThrow('stop here');
    expect(treeFile).toContain('<h1>Store</h1>');
    expect(seen).toMatchObject({ skipSeed: true, prepared: { patched: true } });
    expect(path.basename(seen!.repoDir)).toMatch(/^awt-src-/); // a neutral name: no ref, no patch name
    await expect(readdir(seen!.repoDir)).rejects.toThrow(/ENOENT/); // the tree was removed
    expect(await readFile(path.join(repo, 'web', 'server.cjs'), 'utf8')).toBe(before);
    expect(execFileSync('git', ['-C', repo, 'status', '--porcelain'], { encoding: 'utf8' })).toBe('');
    const entry = (await readRunManifest(path.join(runsDir, runId, 'run.json'))).executions.find((e) => e.execId === 'x-50');
    expect(entry).toMatchObject({ ref: 'golden', patch: 'change.patch', skipSeed: true, executeStatus: 'failed', error: 'Error: stop here' });
  });

  it('refuses a patch that does not apply before recording anything', async () => {
    const patchFile = path.join(root, 'broken.patch');
    await writeFile(patchFile, `--- a/web/server.cjs\n+++ b/web/server.cjs\n@@ -1,1 +1,1 @@\n-no such line\n+other\n`);
    await expect(
      executeRun({ runId, runsDir, targetsDir: path.join(root, 'targets'), projectRoot: root, patch: patchFile, execId: 'x-51' }),
    ).rejects.toThrow(/git apply failed/);
    const manifest = await readRunManifest(path.join(runsDir, runId, 'run.json'));
    expect(manifest.executions.map((e) => e.execId)).not.toContain('x-51');
    expect(await readdir(path.join(runsDir, runId, 'executions'))).not.toContain('x-51');
  });
});

describe('nextExecId', () => {
  it('takes the next number over the folders and run.json, ignoring other names', async () => {
    const dir = await mkdtemp(path.join(root, 'ids-'));
    await mkdir(path.join(dir, 'executions', 'x-03'), { recursive: true });
    await mkdir(path.join(dir, 'executions', 'custom'), { recursive: true });
    const manifest = { executions: [{ execId: 'x-07' }] } as unknown as RunManifest;
    expect(await nextExecId(dir, manifest)).toBe('x-08');
    expect(await nextExecId(path.join(root, 'nothing-here'), { executions: [] } as unknown as RunManifest)).toBe('x-01');
  });
});

describe('measureCoverage (real Playwright)', () => {
  it('runs the passed scripts with backend coverage on, keeps the execution under coverage/ and reads the lines that ran', async () => {
    const runDir = path.join(runsDir, runId);
    const loaded = await loadTargetConfig('fake', { targetsDir: path.join(root, 'targets'), projectRoot: root });
    const config = { ...loaded.config, coverage: { kind: 'node-v8' as const } };
    const measured = await measureCoverage({ runDir, config, repoDir: loaded.repoDir, targetDir: loaded.targetDir, generationRef: 'golden' });

    expect(measured.results.summary).toMatchObject({ total: 7, passed: 4 });
    expect(measured.processes).toBeGreaterThan(0);
    const lines = BACKEND.split('\n');
    const lineOf = (text: string) => lines.findIndex((l) => l.includes(text)) + 1;
    // The request handler ran; a top-level line that runs only at start-up does not count; the frontend is not measured.
    expect(Object.keys(measured.files)).toEqual(['api/server.cjs']);
    expect(measured.files['api/server.cjs']).toContain(lineOf("return json(200, { items: db.items"));
    expect(measured.files['api/server.cjs']).not.toContain(lineOf("const DB = 'db.json'"));
    // The execution moved to coverage/execution/; the raw coverage files are gone; executions/ is untouched.
    expect((await readdir(path.join(runDir, 'coverage'))).sort()).toEqual(['execution', 'flush-on-signal.cjs']);
    expect(ExecutionResults.parse(JSON.parse(await readFile(path.join(runDir, 'coverage', 'execution', 'results.json'), 'utf8'))).execId).toBe('coverage');
    expect(await readdir(path.join(runDir, 'executions'))).not.toContain('coverage');
    expect((await readRunManifest(path.join(runDir, 'run.json'))).executions.map((e) => e.execId)).not.toContain('coverage');
  }, 180_000);
});
