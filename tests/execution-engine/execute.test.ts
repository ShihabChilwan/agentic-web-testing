async function freePort(): Promise<number> {
  const server = http.createServer();
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  const { port } = server.address() as AddressInfo;
  await new Promise((resolve) => server.close(resolve));
  return port;
}

beforeAll(async () => {
  await mkdir(path.join(PROJECT_ROOT, 'runs'), { recursive: true });
  root = await mkdtemp(path.join(PROJECT_ROOT, 'runs', '.execute-test-'));
  const repo = path.join(root, 'targets', 'fake', 'repo');
  for (const sub of ['api', 'web']) {
    await mkdir(path.join(repo, sub, 'node_modules'), { recursive: true });
    await writeFile(path.join(repo, sub, 'package-lock.json'), '{}');
    // Installed for this lockfile: executions link these node_modules into their source tree.
    await writeFile(path.join(repo, sub, 'node_modules', '.lockfile-hash'), `${createHash('sha256').update('{}').digest('hex')}\n`);
  }
  await writeFile(path.join(repo, 'api', 'server.cjs'), BACKEND);
  await writeFile(path.join(repo, 'web', 'server.cjs'), FRONTEND);
  await writeFile(path.join(repo, '.gitignore'), 'db.json\nnode_modules\n');
  const git = (...args: string[]) => execFileSync('git', ['-C', repo, '-c', 'user.name=t', '-c', 'user.email=t@x.test', ...args], { stdio: 'pipe' });
  git('init', '--quiet');
  git('add', '.');
  git('commit', '--quiet', '-m', 'fake app');
  git('branch', 'golden');

  const [backendPort, frontendPort] = [await freePort(), await freePort()];
  const backendUrl = `http://127.0.0.1:${backendPort}`;
  const frontendUrl = `http://127.0.0.1:${frontendPort}`;
  const config = TargetConfig.parse({
    schemaVersion: '1.0', name: 'fake', repoPath: 'targets/fake/repo', repoUrl: 'https://example.test/fake', goldenRef: 'golden',
    backend: {
      cwd: 'api', install: 'true', start: 'node server.cjs', baseUrl: backendUrl, apiPrefix: '/api',
      healthCheckUrl: `${backendUrl}/health`, env: { PORT: String(backendPort) }, disabledServices: {},
    },
    frontend: { cwd: 'web', install: 'true', start: 'node server.cjs', baseUrl: frontendUrl, healthCheckUrl: frontendUrl, env: { PORT: String(frontendPort) } },
    lifecycle: { reset: 'rm -f api/db.json', resetCwd: '.', startupTimeoutMs: 10_000 },
    fixtures: { users: { alice: { email: 'alice@x.test', password: 'pw', role: 'member' } } },
    seed: [{ method: 'POST', path: '/api/auth/register', body: { email: '{{fixtures.users.alice.email}}' } }],
    sourceHints: { include: [], exclude: [] },
    forbiddenPaths: [],
  });
  await writeFile(path.join(root, 'targets', 'fake', 'target.config.json'), JSON.stringify(config));

  runsDir = path.join(root, 'runs');
  const run = await createRun({
    target: 'fake', generationRef: 'golden', generationCommit: 'abc1234', runsDir,
    llm: { provider: 'openai-compatible', models: { prd: 'm', cases: 'm', scripts: 'm', analyzer: 'm' }, temperature: 1, topP: 1, reasoningEffort: { prd: 'low', cases: 'low', scripts: 'low', analyzer: 'low' }, concurrency: 1 },
  });
  runId = run.runId;
  const scriptsDir = run.paths.scriptsDir;
  await mkdir(scriptsDir, { recursive: true });
  for (const [id, text] of Object.entries(SCRIPTS)) await writeFile(path.join(scriptsDir, `${id}.spec.ts`), text);
  await copyFile(path.join(PROJECT_ROOT, 'src', 'modules', 'script-generator', 'template', '_helpers.ts'), path.join(scriptsDir, '_helpers.ts'));
  await writeFile(path.join(scriptsDir, 'manifest.json'), JSON.stringify({ schemaVersion: '1.0', generationRef: 'golden', scripts: MANIFEST_ENTRIES }));
  const cases = ['TC-001', 'TC-002', 'TC-003', 'TC-004', 'TC-005', 'TC-006', 'TC-007', 'TC-008', 'TC-009'].map((id) => testCase(id, id === 'TC-005' ? 'Store' : 1));
  await writeFile(run.paths.testCases, JSON.stringify({ schemaVersion: '1.0', generatedAt: '2026-10-24T10:20:00Z', testCases: cases, coverage: { requirementsTotal: 1, requirementsCovered: 1, uncovered: [], partial: [] } }));
  await setStage(run.paths.dir, 'scripts', { status: 'done' });
});

