import type { TestCase } from '../../shared/schemas.js';

export const LOCK_START = '// @locked-expected';
export const LOCK_END = '// @end-locked-expected';

const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;

/** The EXPECTED block, rendered in code from testcases.json (§6.3). The model never writes it. */
export function renderExpected(tc: TestCase): string {
  const entries = tc.expected.map((e) => {
    const value = e.value === undefined ? '' : `, value: ${typeof e.value === 'string' ? quote(e.value) : String(e.value)}`;
    return `  ${e.id}: { description: ${quote(e.description)}${value} },`;
  });
  return [
    `${LOCK_START} ${tc.id}: generated from testcases.json. Do not edit.`,
    'const EXPECTED = {',
    ...entries,
    '} as const;',
    LOCK_END,
  ].join('\n');
}

/** The test function's parameters: ui tests get the browser page, api tests only the API context. */
export const testParams = (tc: TestCase) => (tc.layer === 'ui' ? '{ page, api }' : '{ api }');

/** Lines of the file before the model's body, so a typecheck error on line N maps to body line N - offset. */
export function header(tc: TestCase): string {
  return [
    `// ${tc.id}: ${tc.title}`,
    '// Generated by agentic-web-testing from testcases.json.',
    "import { bodyOf, expect, fixtures, loggedInPage, loginViaApi, loginViaUi, test, uniq } from './_helpers.js';",
    '',
    renderExpected(tc),
    '',
    `test(${quote(`${tc.id}: ${tc.title}`)}, async (${testParams(tc)}) => {`,
  ].join('\n');
}

/** The whole spec file: header, locked EXPECTED block, and the model-written body inside the test. */
export function renderScript(tc: TestCase, body: string): string {
  const indented = body
    .replace(/\s+$/, '')
    .split('\n')
    .map((l) => (l.trim() === '' ? '' : `  ${l}`))
    .join('\n');
  return `${header(tc)}\n${indented}\n});\n`;
}

export const bodyLineOffset = (tc: TestCase) => header(tc).split('\n').length;
